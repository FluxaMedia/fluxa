import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const rustPath = path.join(root, 'core', 'fluxa-core', 'src', 'runtime', 'effects.rs');
const source = fs.readFileSync(rustPath, 'utf8');
const effects = [...source.matchAll(/EffectKind::([A-Za-z0-9_]+) => "([A-Za-z0-9.]+)"/g)].map((match) => ({
  variant: match[1],
  value: match[2],
}));

if (effects.length === 0) throw new Error('No EffectKind mappings found');
if (new Set(effects.map(({ value }) => value)).size !== effects.length) {
  throw new Error('Duplicate headless effect value found');
}

const actionRustPath = path.join(root, 'core', 'fluxa-core', 'src', 'headless_engine', 'contracts.rs');
const actionSource = fs.readFileSync(actionRustPath, 'utf8');
const actionEnum = actionSource.match(/pub\(super\) enum AppAction \{([\s\S]*?)\n\}\n\n#\[derive/);
if (!actionEnum) throw new Error('AppAction enum not found');
const actions = [...actionEnum[1].matchAll(/#\[serde\(rename = "([^"]+)"\)\]\s*\n\s*[A-Z][A-Za-z0-9_]*/g)].map((match) => match[1]);
if (actions.length === 0) throw new Error('No AppAction mappings found');
if (new Set(actions).size !== actions.length) throw new Error('Duplicate headless action value found');

const checkOnly = process.argv.includes('--check');
const upperFirst = (value) => value.charAt(0).toUpperCase() + value.slice(1);
const lowerFirst = (value) => value.charAt(0).toLowerCase() + value.slice(1);
const outputs = new Map([
  [
    path.join(root, 'shared', 'contracts', 'headless-effects.json'),
    `${JSON.stringify({ effects }, null, 2)}\n`,
  ],
  [
    path.join(root, 'shared', 'contracts', 'headless-actions.json'),
    `${JSON.stringify({ actions }, null, 2)}\n`,
  ],
  [
    path.join(root, 'apps', 'desktop', 'src', 'core', 'generated', 'effectTypes.ts'),
    `// Generated by scripts/generate-headless-contracts.mjs — do not edit.\nexport const EFFECT_TYPE = {\n${effects
      .map(({ variant, value }) => `  ${lowerFirst(variant)}: '${value}',`)
      .join('\n')}\n} as const;\n\nexport const EFFECT_TYPES = [\n${effects
      .map(({ value }) => `  '${value}',`)
      .join('\n')}\n] as const;\n\nexport type EffectType = (typeof EFFECT_TYPES)[number];\n`,
  ],
  [
    path.join(root, 'apps', 'desktop', 'src', 'core', 'generated', 'actionTypes.ts'),
    `// Generated by scripts/generate-headless-contracts.mjs — do not edit.\nexport const APP_ACTION_TYPE = {\n${actions
      .map((value) => `  ${value.replace(/[^A-Za-z0-9]+(.)/g, (_, character) => character.toUpperCase())}: '${value}',`)
      .join('\n')}\n} as const;\n\nexport const APP_ACTION_TYPES = [\n${actions
      .map((value) => `  '${value}',`)
      .join('\n')}\n] as const;\n\nexport type AppActionType = (typeof APP_ACTION_TYPES)[number];\n`,
  ],
  [
    path.join(
      root,
      'apps',
      'android',
      'core',
      'src',
      'commonMain',
      'kotlin',
      'com',
      'fluxa',
      'app',
      'core',
      'rust',
      'GeneratedHeadlessActionTypes.kt',
    ),
    `// Generated by scripts/generate-headless-contracts.mjs — do not edit.\npackage com.fluxa.app.core.rust\n\nobject FluxaHeadlessActionType {\n${actions
      .map((value) => `    const val ${upperFirst(value.replace(/[^A-Za-z0-9]+(.)/g, (_, character) => character.toUpperCase()))} = "${value}"`)
      .join('\n')}\n\n    val all: Set<String> = setOf(\n${actions
      .map((value) => `        ${upperFirst(value.replace(/[^A-Za-z0-9]+(.)/g, (_, character) => character.toUpperCase()))},`)
      .join('\n')}\n    )\n}\n`,
  ],
  [
    path.join(
      root,
      'apps',
      'android',
      'core',
      'src',
      'commonMain',
      'kotlin',
      'com',
      'fluxa',
      'app',
      'core',
      'rust',
      'GeneratedHeadlessEffectTypes.kt',
    ),
    `// Generated by scripts/generate-headless-contracts.mjs — do not edit.\npackage com.fluxa.app.core.rust\n\nobject FluxaHeadlessEffectType {\n${effects
      .map(({ variant, value }) => `    const val ${upperFirst(variant)} = "${value}"`)
      .join('\n')}\n\n    val all: Set<String> = setOf(\n${effects
      .map(({ variant }) => `        ${upperFirst(variant)},`)
      .join('\n')}\n    )\n}\n`,
  ],
  [
    path.join(root, 'apps', 'apple', 'AppleCore', 'FluxaHeadlessEffectType.swift'),
    `// Generated by scripts/generate-headless-contracts.mjs — do not edit.\nenum FluxaHeadlessEffectType {\n${effects
      .map(({ variant, value }) => `    static let ${lowerFirst(variant)} = "${value}"`)
      .join('\n')}\n\n    static let all: Set<String> = [\n${effects
      .map(({ variant }) => `        ${lowerFirst(variant)},`)
      .join('\n')}\n    ]\n}\n`,
  ],
  [
    path.join(root, 'apps', 'apple', 'AppleCore', 'FluxaHeadlessActionType.swift'),
    `// Generated by scripts/generate-headless-contracts.mjs — do not edit.\nenum FluxaHeadlessActionType {\n${actions
      .map((value) => `    static let ${lowerFirst(value)} = "${value}"`)
      .join('\n')}\n\n    static let all: Set<String> = [\n${actions
      .map((value) => `        ${lowerFirst(value)},`)
      .join('\n')}\n    ]\n}\n`,
  ],
]);

for (const [outputPath, content] of outputs) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current === content) continue;
  if (checkOnly) throw new Error(`generated headless contract is out of date: ${path.relative(root, outputPath)}`);
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, content);
}

if (!checkOnly) process.stdout.write(`generated ${effects.length} headless effect types and ${actions.length} headless action types\n`);
